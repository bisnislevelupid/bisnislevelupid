export function columnLabel(name: string) {
  if (COLUMN_LABELS[name]) return COLUMN_LABELS[name];
  return name
    .split("_")
    .map((part) => TOKEN[part] ?? part)
    .join(" ");
}

export function tableLabel(table: string) {
  return TABLE_LABELS[table] ?? columnLabel(table);
}

export function pickVisibleColumns(table: string, available: string[], pk: string) {
  const have = new Set(available);
  const preferred = (COLUMN_PRIORITY[table] ?? []).filter((name) => have.has(name));
  if (preferred.length) return preferred;
  const skip = new Set([
    pk,
    "password_hash",
    "token_hash",
    "guidance_text",
    "long_desc",
    "description",
    "gate_desc",
    "content",
    "message_content",
    "request_payload",
    "response_payload",
    "qr_string",
    "payment_url",
    "snap_token",
    "user_agent",
    "crisis_desc",
  ]);
  const ordered = available.filter((name) => !skip.has(name));
  const foreign = ordered.filter((name) => name.endsWith("_id") || name === "created_by");
  const plain = ordered.filter((name) => !name.endsWith("_id") && name !== "created_by");
  const picked: string[] = [];
  for (const name of [...plain.slice(0, 4), ...foreign, ...plain.slice(4)]) {
    if (picked.includes(name)) continue;
    picked.push(name);
    if (picked.length >= 8) break;
  }
  return picked.length ? picked : available.filter((name) => name !== "password_hash").slice(0, 6);
}

export function fieldOptions(table: string, column: string) {
  if (column === "status" && (table === "customers" || table === "affiliates" || table === "testimonials")) {
    return ACTIVE_STATUS;
  }
  return FIELD_OPTIONS[column] ?? null;
}
